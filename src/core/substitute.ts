/**
 * 安全な文字の中に代わりが無いもの。
 *
 * 4 分割ブロックの単独クォーター `▘▝▖▗` は「1 マスを 2×2 の点として使う」ための
 * 文字で、半分ブロックの上 `▀`・右 `▐` も使えない以上どうやっても表現できない。
 * `▜`（上＋右）も同じ理由。`◡` は下向きの弧で、`⌒` の上下反転が存在しない。
 */
export const NO_SUBSTITUTE = new Set(Array.from('▘▝▖▗▜◡'));

export interface SubstituteResult {
    text: string;
    /** 置き換えた文字（元 → 先）。UI で「何を何に変えたか」を出すのに使う */
    replaced: { from: string; to: string }[];
    /** 代わりが無く手つかずで残った文字 */
    unresolved: string[];
}

/**
 * 使用不可の文字を安全な文字へ置き換える。
 * @param approx true なら見た目が変わる置き換えも適用する
 */
export function substituteUnsafe(text: string, approx = false): SubstituteResult {
    const table = approx
        ? { ...EXACT_SUBSTITUTIONS, ...APPROX_SUBSTITUTIONS }
        : EXACT_SUBSTITUTIONS;
    const replaced = new Map<string, string>();
    const unresolved = new Set<string>();

    const out = Array.from(text)
        .map((c) => {
            const to = table[c];
            if (to !== undefined) {
                replaced.set(c, to);
                return to;
            }
            if (UNSAFE_DISPLAY_CHARS.has(c)) unresolved.add(c);
            return c;
        })
        .join('');

    return {
        text: out,
        replaced: [...replaced].map(([from, to]) => ({ from, to })),
        unresolved: [...unresolved],
    };
}
