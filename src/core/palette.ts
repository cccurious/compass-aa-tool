/**
 * 一度パレットに載せたが取り下げた文字（2026-07-26）。
 * ユーザーの端末に保存済みの「最近使った」「追加分」からも消すため、
 * ストアの読み込み時にこの集合で濾す。
 *
 * どちらも**実機のフォントにグリフが無い**ことが原因（文字自体は削除されず
 * コピーバックには残るが、画面には出ない）。実機プローブ `█▘█▝█▖█▗█▚…` の
 * 折り返し位置をピクセル測定して確定（詳細は calibration-plan.md）。
 *
 * - 4 分割ブロック `▘▝▖▗▚▞▛▜▙▟`(U+2598-259F): **幅 0 で完全に見えない**。
 *   「1 マスを 2×2 の点として使う」機能ごと成立しないため撤去。
 * - 濃淡 `░▒▓` と上 `▀`・右 `▐`: iOS だけ 46/64 幅（折り返し個数法で確定。
 *   当初の「半分」は目視の誤り）。**下 `▄`・左 `▌` は全角幅で生存**。
 * - `↕`: iOS だけ半分の幅・0.5 ちょうど（`↑↓↔` は全角のまま）
 * - 二重罫線 U+2550-256C: 29 文字全数を個別実測し、`═╞╡╪` の 4 つだけ全角で
 *   復帰。残り 25 文字は iOS 46/64（太線・細線の罫線は全角のまま）
 *
 * 教訓: 「同じ Unicode ブロックだから同じ挙動」は成り立たない。
 * **同じ半分ブロックの 4 方向ですら、下 ▄・左 ▌ は出るのに上 ▀・右 ▐ は落ちる。**
 * 濃淡は 3 段とも半分、4 分割は 10 個とも不可視、罫線は二重線だけ落ちる。
 * 字形や用途からは全く予測できないので、
 * **新しい文字をパレットに載せる前に、必ず 1 文字ずつ実機で目視する。**
 */
